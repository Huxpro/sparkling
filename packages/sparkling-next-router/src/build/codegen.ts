import fs from 'node:fs';
import path from 'node:path';
import { bundleNameForPattern, compilePattern } from '../shared/manifest';
import type { ScannedRoute } from './scan';

export interface CodegenResult {
  /** Entry name → absolute generated entry file path (for rspeedy source.entry). */
  entries: Record<string, string>;
  /** Absolute path of the generated manifest module. */
  manifestFile: string;
}

const HEADER = `// Generated by sparkling-next-router. Do not edit.\n`;

function relImport(fromDir: string, target: string): string {
  let rel = path.relative(fromDir, target).replace(/\\/g, '/');
  rel = rel.replace(/\.(tsx|ts|jsx|js)$/, '');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

/**
 * Emit `.sparkling/next-router/` containing the route manifest module and
 * one bundle entry per route.
 */
export function generateRouteModules(
  cwd: string,
  routes: ScannedRoute[],
  options: { baseScheme?: string; outDir?: string } = {},
): CodegenResult {
  const baseScheme = options.baseScheme ?? 'hybrid://lynxview_page';
  const outDir = path.resolve(cwd, options.outDir ?? '.sparkling/next-router');
  fs.mkdirSync(outDir, { recursive: true });

  const compiled = routes.map((route) => {
    const { paramNames, regexSource, kind } = compilePattern(route.pattern);
    const bundle = bundleNameForPattern(route.pattern);
    return { route, paramNames, regexSource, kind, bundle };
  });

  const byBundle = new Map<string, string>();
  for (const c of compiled) {
    const existing = byBundle.get(c.bundle);
    if (existing) {
      throw new Error(
        `sparkling-next-router: bundle name collision '${c.bundle}' between routes '${existing}' and '${c.route.pattern}'`,
      );
    }
    byBundle.set(c.bundle, c.route.pattern);
  }

  const manifestFile = path.join(outDir, 'manifest.ts');
  const manifestSource = `${HEADER}
import type { RouteManifest } from 'sparkling-next-router/runtime';

export const routeManifest: RouteManifest = {
  baseScheme: ${JSON.stringify(baseScheme)},
  routes: [
${compiled
  .map(
    (c) => `    {
      pattern: ${JSON.stringify(c.route.pattern)},
      bundle: ${JSON.stringify(c.bundle)},
      paramNames: ${JSON.stringify(c.paramNames)},
      regexSource: ${JSON.stringify(c.regexSource)},
      kind: ${JSON.stringify(c.kind)},
    },`,
  )
  .join('\n')}
  ],
};
`;
  writeIfChanged(manifestFile, manifestSource);

  const entries: Record<string, string> = {};
  for (const c of compiled) {
    const entryFile = path.join(outDir, `${c.bundle}.entry.tsx`);
    const layoutImports = c.route.layoutFiles
      .map((file, i) => `import Layout${i} from '${relImport(outDir, file)}';`)
      .join('\n');
    const layoutIdents = c.route.layoutFiles.map((_, i) => `Layout${i}`).join(', ');
    const notFoundImport = c.route.notFoundFile
      ? `import NotFound from '${relImport(outDir, c.route.notFoundFile)}';`
      : 'const NotFound = undefined;';
    const loadingImport = c.route.loadingFile
      ? `import Loading from '${relImport(outDir, c.route.loadingFile)}';`
      : 'const Loading = undefined;';

    const source = `${HEADER}
import { root } from '@lynx-js/react';
import { SparklingNextRoot } from 'sparkling-next-router/runtime';
import { routeManifest } from './manifest';
import Page from '${relImport(outDir, c.route.pageFile)}';
${layoutImports}
${notFoundImport}
${loadingImport}

root.render(
  <SparklingNextRoot
    manifest={routeManifest}
    route=${JSON.stringify(c.route.pattern)}
    layouts={[${layoutIdents}]}
    page={Page}
    notFound={NotFound}
    loading={Loading}
  />,
);
`;
    writeIfChanged(entryFile, source);
    entries[c.bundle] = entryFile;
  }

  // Remove stale generated entries from previous runs.
  for (const file of fs.readdirSync(outDir)) {
    if (!file.endsWith('.entry.tsx')) continue;
    const bundle = file.replace(/\.entry\.tsx$/, '');
    if (!entries[bundle]) fs.rmSync(path.join(outDir, file));
  }

  return { entries, manifestFile };
}

function writeIfChanged(file: string, content: string): void {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return;
  fs.writeFileSync(file, content);
}
